#!/usr/bin/env python3
"""Generate the native/.NET API from the pinned, unmodified WASM wrapper.

Only transport syntax changes: wasm annotations, JS values/errors, JSON and
base64 byte buffers. Engine calls, argument order and method bodies stay upstream.
Run with --check in validation; without it to update generated files after a pin.
"""
from pathlib import Path
import argparse
import hashlib
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'bindings/wasm/src/lib.rs'
source = SOURCE.read_text()
digest = hashlib.sha256(source.encode()).hexdigest()
banner = f'// Generated by tools/cyancalc/sync-wasm-binding.py from bindings/wasm/src/lib.rs\n// Source SHA256: {digest}. Do not edit this file by hand.\n'


def strip_attributes(text):
    return re.sub(r'#\[wasm_bindgen(?:\((?:"[^"]*"|[^"\)])*\))?\]\s*', '', text)


def camel(name):
    parts = name.split('_')
    return parts[0] + ''.join(p[:1].upper() + p[1:] for p in parts[1:])


functions = []
last_end = 0
for match in re.finditer(r'pub fn (\w+)\(', source):
    start = match.start()
    body = source.index('{', start)
    header = strip_attributes(source[start:body])
    name, args, returns = re.fullmatch(r'pub fn (\w+)\((.*?)\)\s*(?:->\s*(.*?))?\s*', header, re.S).groups()
    names = re.findall(r'js_name\s*=\s*"([^"]+)"', source[last_end:start])
    js_name = names[-1] if names else name
    params = []
    receiver = None
    for arg in args.split(','):
        arg = arg.strip()
        if not arg:
            continue
        if arg in ('&self', '&mut self'):
            receiver = arg
        else:
            key, kind = arg.split(':', 1)
            params.append((key.strip(), kind.strip()))
    depth, end = 1, body + 1
    while depth:
        if source[end] == '{': depth += 1
        if source[end] == '}': depth -= 1
        end += 1
    last_end = end
    functions.append(dict(name=name, js=js_name, params=params, receiver=receiver,
                          returns=(returns or '()').strip(), model=start > source.index('impl Model {')))

native = strip_attributes(source)
native = re.sub(r'use wasm_bindgen::\{.*?\};',
                'use crate::wasm_support::{JsError, JsValue};\nuse crate::wasm_support as serde_wasm_bindgen;', native, flags=re.S)
native = native.replace('ironcalc_base', 'ironcalc::base')
native = native.replace('#[cfg(feature = "xlsx")]\n', '')
native = native.replace('    model: BaseModel<\'static>,', '    pub(crate) model: BaseModel<\'static>,')
native = native.replace('.serialize(&serde_wasm_bindgen::Serializer::json_compatible())',
                        '.serialize(serde_json::value::Serializer)')
native = banner + native


def rust_arg(key, kind):
    if kind == '&str': return f'text(request, "{key}")?'
    if kind == '&[u8]': return f'&bytes(request, "{key}")?'
    if kind.startswith('Option<'): return f'optional(request, "{key}")?'
    return f'arg(request, "{key}")?'


dispatch = banner + '''use crate::{upstream_api, protocol::{arg, optional, text, value}};
use base64::{engine::general_purpose::STANDARD, Engine};
use serde_json::Value;

fn bytes(request: &Value, key: &str) -> Result<Vec<u8>, String> {
    STANDARD.decode(text(request, key)?).map_err(|e| e.to_string())
}
'''
for is_model, method in ((True, 'dispatch'), (False, 'utility')):
    selected = [f for f in functions if f['model'] == is_model]
    receiver = 'model: &mut upstream_api::Model, ' if is_model else ''
    dispatch += f'pub fn {method}({receiver}request: &Value) -> Option<Result<Value, String>> {{\n'
    dispatch += '    Some((|| { match text(request, "op")? {\n'
    for f in selected:
        target = 'model.' if f['receiver'] else ('upstream_api::Model::' if is_model else 'upstream_api::')
        call = target + f['name'] + '(' + ', '.join(rust_arg(*a) for a in f['params']) + ')'
        result_type = f['returns']
        if result_type.startswith('Result<'):
            result_type = result_type[7:-len(', JsError>')]
            call += '.map_err(|e| e.to_string())?'
        if result_type == 'Model':
            expression = f'{{ let next = {call}; *model = next; Ok(Value::Null) }}'
        elif result_type == 'Vec<u8>':
            expression = f'value(STANDARD.encode({call}))'
        else:
            expression = f'value({call})'
        dispatch += f'        "{f["js"]}" => {expression},\n'
    dispatch += '        _ => unreachable!(),\n    } })())\n}\n'
    # Unknown operations are left to the desktop adapter, without executing it twice.
    names = ' | '.join('"' + f['js'] + '"' for f in selected)
    marker = f'pub fn {method}({receiver}request: &Value) -> Option<Result<Value, String>> {{\n'
    dispatch = dispatch.replace(marker, marker + f'    if !matches!(request.get("op").and_then(Value::as_str)?, {names}) {{ return None; }}\n')

dispatch += 'pub fn legacy_name(op: &str) -> Option<&\'static str> { match op {\n'
for f in functions:
    if f['name'] != f['js']:
        dispatch += f'    "{f["name"]}" => Some("{f["js"]}"),\n'
dispatch += '    _ => None,\n} }\n'

cs_types = {'&str': 'string', '&[u8]': 'byte[]', 'i32': 'int', 'u32': 'int', 'usize': 'int',
            'f64': 'double', 'bool': 'bool', 'JsValue': 'JsonElement', 'Option<u32>': 'int?',
            'Option<String>': 'string?', 'Option<i32>': 'int?', 'String': 'string', 'Vec<String>': 'string[]',
            'Vec<i32>': 'int[]', 'Vec<u8>': 'byte[]', '()': 'void'}
cs_returns = {'get_cell_type': 'CellType', 'get_cell_link': 'JsonElement?',
              'get_links': 'JsonElement[]', 'get_worksheets_properties': 'WorksheetInfo[]',
              'get_selected_view': 'SelectedView', 'get_merged_cells': 'MergedCell[]',
              'get_defined_name_list': 'DefinedName[]',
              'get_selected_cell': '(int Sheet, int Row, int Column)'}
area_methods = {'update_range_style', 'merge_cells', 'merge_cells_center', 'merge_cells_across',
                'merge_cells_down', 'unmerge_cells', 'set_area_with_border', 'auto_fill_rows',
                'auto_fill_columns', 'paste_csv_string'}
cs_files = {}
for is_model, cls in ((True, 'UserModel'), (False, 'ReferenceUtils')):
    cs = banner + '#nullable enable\nusing System.Text.Json;\n\nnamespace CyanCalc;\n\n'
    cs += ('public sealed partial class ' if is_model else 'public static partial class ') + cls + '\n{\n'
    for f in [f for f in functions if f['model'] == is_model and f['name'] != 'new']:
        params, values = [], []
        for key, kind in f['params']:
            param = camel(key)
            ctype = cs_types[kind]
            if key == 'source_range': ctype = 'int[]'
            if f['name'] in area_methods and key in ('range', 'area', 'source_area'):
                ctype = 'CellArea'
            default = ' = null' if kind.startswith('Option<') and key == f['params'][-1][0] else ''
            if f['name'] == 'from_bytes' and key == 'language_id': default = ' = "en"'
            params.append(f'{ctype} {param}{default}')
            encoded = f'Convert.ToBase64String({param})' if kind == '&[u8]' else param
            values.append(f'{key} = {encoded}')
        args = ', new { ' + ', '.join(values) + ' }' if values else ''
        method = f['js'][0].upper() + f['js'][1:]
        rt = f['returns']
        if rt.startswith('Result<'): rt = rt[7:-len(', JsError>')]
        returns = 'UserModel' if rt == 'Model' else cs_returns.get(f['name'], cs_types.get(rt))
        assert returns, rt
        static = 'static ' if not f['receiver'] else ''
        if rt == 'Model':
            expression = f'FromNative("{f["js"]}"{args})'
        elif not is_model:
            expression = f'Call<{returns}>("{f["js"]}"{args})'
        elif returns == 'void':
            action = 'Execute' if f['receiver'] == '&mut self' and f['name'] != 'is_valid_defined_name' else 'Query'
            expression = f'{action}("{f["js"]}"{args})'
        elif f['name'] == 'get_selected_cell':
            expression = f'SelectedCellTuple(Query<int[]>("{f["js"]}"{args}))'
        elif rt == 'Vec<u8>':
            expression = f'Convert.FromBase64String(Query<string>("{f["js"]}"{args}))'
        elif returns == 'CellType':
            expression = f'(CellType)Query<int>("{f["js"]}"{args})'
        elif returns == 'JsonElement?':
            expression = f'NullableJson(Query("{f["js"]}"{args}))'
        elif returns == 'int?':
            expression = f'Query("{f["js"]}"{args}).Deserialize<int?>()'
        elif returns == 'JsonElement':
            expression = f'Query("{f["js"]}"{args})'
        else:
            expression = f'Query<{returns}>("{f["js"]}"{args})'
        cs += f'    public {static}{returns} {method}({", ".join(params)}) =>\n        {expression};\n'
    cs += '}\n'
    cs_files[f'bindings/dotnet/{cls}.Wasm.g.cs'] = cs

outputs = {'bindings/dotnet/native/src/upstream_api.rs': native,
           'bindings/dotnet/native/src/upstream_dispatch.rs': dispatch, **cs_files}
with tempfile.TemporaryDirectory() as temp:
    for name in list(outputs):
        if name.endswith('.rs'):
            path = Path(temp) / Path(name).name
            path.write_text(outputs[name])
            subprocess.run(['rustfmt', '--edition', '2021', str(path)], check=True)
            outputs[name] = path.read_text()

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
check = parser.parse_args().check
stale = []
for name, content in outputs.items():
    path = ROOT / name
    if check:
        if not path.exists() or path.read_text() != content: stale.append(name)
    else:
        path.write_text(content)
if stale:
    raise SystemExit('Generated WASM binding differs: ' + ', '.join(stale))
print(f'WASM_BINDING_{"CHECK" if check else "SYNC"}_PASS: {sum(f["model"] for f in functions)} model exports, {sum(not f["model"] for f in functions)} utilities; source {digest}')
